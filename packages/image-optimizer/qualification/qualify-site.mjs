// Site qualification of the native image optimizer: builds a disposable EmDash site from the patched
// pilot host (Node adapter, SQLite, local storage, `safeMedia`), registers the plugin, and drives it
// over HTTP as a signed-in admin. It checks apply, restore, re-optimization, bulk runs, delivery
// freshness, authorization, the plugin lifecycle (upgrade, disable, re-enable, uninstall, reinstall),
// the sandboxed edition and the rollback through the host's recovery entry point.
//
//   node packages/image-optimizer/qualification/qualify-site.mjs --pilot <emdash-pilot worktree>
//     [--work <directory>] [--port <port>] [--patch-manifest <patches.json>] [--no-evidence]
//     [--runner process | --runner systemd --site-user <user> [--unit <name>] [--memory-max 3G]
//      [--cpu-quota 200%] [--build-wrapper <executable>]]
//
// Runners. `process` (the default) starts the site as a child of this script, as in a container.
// `systemd` is the hosted profile: run as root on the host, it starts the site as a transient systemd
// service under the site user, with the memory and CPU caps and the sandboxing in `systemd.mjs`, its
// data directories owned by that user with mode 0700, and checks those, the cgroup, the processor's
// workers and out-of-memory events besides everything else. Build steps can then run elsewhere
// through `--build-wrapper` (see `useBuildWrapper` in `site.mjs`); the site itself runs with the Node
// binary running this script.
//
// The site binds to 127.0.0.1 only. Every image is generated by Sharp, and the admin and editor
// sign in with in-memory software passkeys created for the run. Evidence is written beside this
// script only when every check passed: `site-latest.json` for the process runner,
// `site-host-latest.json` for the systemd runner, and `site-proxy-latest.json` or
// `site-host-proxy-latest.json` with `--proxy caddy`.
//
// Proxy. `--proxy caddy [--proxy-port <port>] [--proxy-image <image>]` starts a throwaway Caddy on
// 127.0.0.1 in front of the site (`proxy.mjs`: a `caddy` binary, or a container of the image on the
// host's network) and sends every request of the run to the proxy instead of the site's port. The
// site's URL and the passkeys' origin are then the proxy's. It checks besides that the proxy's
// configuration only passes requests on, and that every response measured came through it.
