/** Sharp-generated photograph-like JPEGs (gradient, texture and grain), saved heavier than needed. */
async function fixtures(sharp, count) {
  const images = [];
  for (let index = 0; index < count; index += 1) {
    const width = 1024;
    const height = 768;
    const hue = (index * 37) % 360;
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}">
      <defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
        <stop offset="0" stop-color="hsl(${hue},70%,55%)"/><stop offset="1" stop-color="hsl(${(hue + 140) % 360},60%,35%)"/>
      </linearGradient></defs>
      <rect width="100%" height="100%" fill="url(#g)"/>
      <circle cx="${300 + index * 40}" cy="380" r="${150 + index * 5}" fill="hsl(${(hue + 60) % 360},80%,70%)" opacity="0.6"/>
    </svg>`;
    const grain = await sharp({ create: { width, height, channels: 3, noise: { type: 'gaussian', mean: 128, sigma: 18 } } }).raw().toBuffer();
    const bytes = await sharp(Buffer.from(svg))
      .composite([{ input: grain, raw: { width, height, channels: 3 }, blend: 'overlay' }])
      .jpeg({ quality: 100, chromaSubsampling: '4:4:4' })
      .toBuffer();
    images.push({ name: `fixture-${String(index + 1).padStart(2, '0')}.jpg`, bytes, width, height });
  }
  return images;
}

