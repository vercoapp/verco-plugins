// --- Delivery ----------------------------------------------------------------------------------

const fileUrl = (key) => `/_emdash/api/media/file/${key}`;
const transformedUrl = (key) => `/_image?href=${encodeURIComponent(fileUrl(key))}&w=320&f=png`;

async function fetchBytes(path, init = {}) {
  const response = await fetch(`${origin}${path}`, { redirect: 'manual', ...init });
  const bytes = Buffer.from(await response.arrayBuffer());
  return {
    status: response.status,
    sha256: sha256(bytes),
    bytes,
    cacheControl: response.headers.get('cache-control'),
    etag: response.headers.get('etag'),
    lastModified: response.headers.get('last-modified'),
    via: response.headers.get('via'),
    age: response.headers.get('age'),
  };
}

/**
 * Requests the direct and transformed URLs right after a mutation answered, until each serves the
 * expected content: the direct URL the expected digest, the transformed URL something other than
 * its previous output (or exactly its earlier output, after a byte-exact restore).
 */
async function freshness(event, key, { directSha, directNot, transformedNot, transformedSha }) {
  const measure = async (path, fresh) => {
    const begin = performance.now();
    let stale = 0;
    for (;;) {
      const got = await fetchBytes(path);
      // Through the proxy, every response measured must have come through it.
      if (proxied) assert.match(got.via ?? '', /caddy/i, `${event}: ${path} was not answered through the proxy`);
      if (got.status === 200 && fresh(got)) {
        const measured = { staleResponses: stale, msToFresh: Number((performance.now() - begin).toFixed(1)), cacheControl: got.cacheControl, etag: got.etag, sha256: got.sha256 };
        return proxied ? { ...measured, via: got.via, age: got.age } : measured;
      }
      stale += 1;
      if (performance.now() - begin > 30_000) throw new Error(`${event}: ${path} still stale after 30 s (${stale} responses)`);
      await sleep(100);
    }
  };
  const direct = await measure(fileUrl(key), (got) => (directSha ? got.sha256 === directSha : got.sha256 !== directNot));
  const transformed = await measure(transformedUrl(key), (got) =>
    transformedSha ? got.sha256 === transformedSha : got.sha256 !== transformedNot,
  );
  return { event, direct, transformed };
}

