/** The commit of this checkout and whether it had changes when the run began, or null outside git. */
function sourceState() {
  try {
    const git = (...parameters) => build('git', parameters, { cwd: repository }).trim();
    // Evidence files an earlier run of this checkout wrote are not changes to what runs.
    const changed = git('status', '--porcelain').split('\n').filter((line) => line && !/qualification\/site(-host)?(-proxy)?-latest\.json$/.test(line));
    return { commit: git('rev-parse', 'HEAD'), uncommittedChanges: changed.length };
  } catch {
    return null;
  }
}
