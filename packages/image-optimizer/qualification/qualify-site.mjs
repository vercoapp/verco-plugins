/** Each passed check, in order, with what it established. */
const checks = [];
function passed(name, details = {}) {
  checks.push({ name, ...details });
  log(`ok  ${name}`);
}

async function waitFor(what, probe, { timeoutMs = 240_000, intervalMs = 3_000 } = {}) {
  const deadline = Date.now() + timeoutMs;
  for (;;) {
    const value = await probe();
    if (value) return value;
    if (Date.now() > deadline) throw new Error(`Timed out waiting for ${what}`);
    await sleep(intervalMs);
  }
}

// --- Site state: database rows and files -----------------------------------------------------

function database() {
  return new DatabaseSync(paths.database, { readOnly: true });
}

function query(sql, ...parameters) {
  const db = database();
  try {
    return db.prepare(sql).all(...parameters);
  } finally {
    db.close();
  }
}

function filesUnder(directory) {
  const out = {};
  const walk = (current) => {
    let entries;
    try {
      entries = readdirSync(current, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries) {
      const path = join(current, entry.name);
      if (entry.isDirectory()) walk(path);
      else if (entry.isFile()) out[relative(directory, path)] = sha256(readFileSync(path));
    }
  };
  walk(directory);
  return out;
}

/**
 * What a refused request must not change: media rows, the host's revisions, originals and
 * operations, the plugin's storage, settings and key-value rows, its scheduled tasks, and every file
 * in public storage, the private originals store and the plugin's staging directory.
 */
function snapshot() {
  const db = database();
  try {
    const rows = (sql) => sha256(JSON.stringify(db.prepare(sql).all()));
    return {
      media: rows('SELECT * FROM media ORDER BY id'),
      revisions: rows('SELECT * FROM _emdash_media_revisions ORDER BY id'),
      originals: rows('SELECT * FROM _emdash_media_originals ORDER BY sha256'),
      operations: rows('SELECT * FROM _emdash_media_operations ORDER BY operation_id'),
      pluginStorage: rows(`SELECT * FROM _plugin_storage WHERE plugin_id = '${PLUGIN}' ORDER BY collection, id`),
      pluginOptions: rows(`SELECT * FROM options WHERE name LIKE 'plugin:${PLUGIN}:%' ORDER BY name`),
      cron: rows(`SELECT id, plugin_id, task_name, schedule, enabled, status FROM _emdash_cron_tasks WHERE plugin_id = '${PLUGIN}' ORDER BY id`),
      uploads: sha256(JSON.stringify(filesUnder(paths.uploads))),
      private: sha256(JSON.stringify(filesUnder(paths.private))),
      staging: sha256(JSON.stringify(filesUnder(paths.staging))),
    };
  } finally {
    db.close();
  }
}

function changedParts(before, after) {
  return Object.keys(before).filter((key) => before[key] !== after[key]);
}

function mediaRow(id) {
  return query('SELECT * FROM media WHERE id = ?', id)[0];
}

function activeRevision(id) {
  return query('SELECT r.* FROM media m JOIN _emdash_media_revisions r ON r.id = m.revision_id WHERE m.id = ?', id)[0] ?? null;
}

function operations(id) {
  return query('SELECT operation_id, kind, state, expected_revision_id, candidate_revision_id, candidate_sha256, original_sha256 FROM _emdash_media_operations WHERE media_id = ? ORDER BY created_at, operation_id', id);
}

function pluginRows() {
  return query(`SELECT collection, COUNT(*) AS count FROM _plugin_storage WHERE plugin_id = '${PLUGIN}' GROUP BY collection ORDER BY collection`);
}

// --- Delivery ----------------------------------------------------------------------------------

const fileUrl = (key) => `/_emdash/api/media/file/${key}`;
const transformedUrl = (key) => `/_image?href=${encodeURIComponent(fileUrl(key))}&w=320&f=png`;

async function fetchBytes(path, init = {}) {
  const response = await fetch(`${origin}${path}`, { redirect: 'manual', ...init });
  const bytes = Buffer.from(await response.arrayBuffer());
  return {
    status: response.status,
    sha256: sha256(bytes),
    bytes,
    cacheControl: response.headers.get('cache-control'),
    etag: response.headers.get('etag'),
    lastModified: response.headers.get('last-modified'),
  };
}

/**
 * Requests the direct and transformed URLs right after a mutation answered, until each serves the
 * expected content: the direct URL the expected digest, the transformed URL something other than
 * its previous output (or exactly its earlier output, after a byte-exact restore).
 */
async function freshness(event, key, { directSha, directNot, transformedNot, transformedSha }) {
  const measure = async (path, fresh) => {
    const begin = performance.now();
    let stale = 0;
    for (;;) {
      const got = await fetchBytes(path);
      if (got.status === 200 && fresh(got)) {
        return { staleResponses: stale, msToFresh: Number((performance.now() - begin).toFixed(1)), cacheControl: got.cacheControl, etag: got.etag, sha256: got.sha256 };
      }
      stale += 1;
      if (performance.now() - begin > 30_000) throw new Error(`${event}: ${path} still stale after 30 s (${stale} responses)`);
      await sleep(100);
    }
  };
  const direct = await measure(fileUrl(key), (got) => (directSha ? got.sha256 === directSha : got.sha256 !== directNot));
  const transformed = await measure(transformedUrl(key), (got) =>
    transformedSha ? got.sha256 === transformedSha : got.sha256 !== transformedNot,
  );
  return { event, direct, transformed };
}

