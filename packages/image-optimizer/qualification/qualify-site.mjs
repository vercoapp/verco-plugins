// --- The hosted profile: the unit, its cgroup, its processes and its data ------------------------

/**
 * On each start under systemd: the caps are the kernel's for the unit's cgroup, and exactly one site
 * server runs, in that cgroup, as the site user.
 */
function checkUnit(label) {
  const cgroup = hosted.cgroup();
  assert.equal(cgroup.memoryMax, hosted.expected.memoryMax, `${label}: memory.max`);
  assert.equal(cgroup.swapMax, hosted.expected.swapMax, `${label}: memory.swap.max`);
  assert.equal(cgroup.cpuMax, hosted.expected.cpuMax, `${label}: cpu.max`);
  const servers = hosted.siteProcesses().filter((entry) => entry.role === 'server');
  assert.equal(servers.length, 1, `${label}: ${servers.length} site server processes`);
  assert.equal(servers[0].cgroup, cgroup.path, `${label}: the site server runs outside the unit's cgroup`);
  assert.equal(servers[0].pid, site.pid, `${label}: the site server is not the unit's main process`);
  const owner = /^Uid:\s+(\d+)\s+(\d+)/m.exec(readFileSync(`/proc/${servers[0].pid}/status`, 'utf8'));
  assert.deepEqual([Number(owner[1]), Number(owner[2])], [hosted.uid, hosted.uid], `${label}: the site server does not run as the site user`);
  return cgroup;
}

/** The processor's workers seen while sampling: there were some, and all ran in the unit's cgroup. */
function checkWorkers(label, seen) {
  const unitCgroup = hosted.cgroup().path;
  const workers = seen.filter((entry) => entry.role === 'worker');
  const outside = seen.filter((entry) => entry.cgroup !== unitCgroup);
  assert.ok(workers.length > 0, `${label}: no processor worker was seen`);
  assert.deepEqual(outside.map((entry) => ({ pid: entry.pid, role: entry.role, cgroup: entry.cgroup })), [], `${label}: site processes outside the unit's cgroup`);
  return { workersSeen: workers.length, processesSeen: seen.length };
}

/**
 * The data directory, the database and the private originals belong to the site user alone:
 * directories 0700, the database 0600 and every other file without group or other access, and
 * another unprivileged user can read none of them.
 */
function checkDataPermissions(label) {
  const { entries, problems } = hosted.inspectData();
  assert.deepEqual(problems, [], `${label}: data entries with the wrong owner or mode`);
  const mode = (path) => entries.find((entry) => entry.path === (relative(paths.data, path) || '.'))?.mode;
  assert.equal(mode(paths.database), 0o600, `${label}: database mode`);
  assert.equal(mode(paths.private), 0o700, `${label}: private directory mode`);
  assert.equal(mode(paths.data), 0o700, `${label}: data directory mode`);
  const privateFiles = Object.keys(filesUnder(paths.private)).map((path) => join(paths.private, path));
  const uploadFiles = Object.keys(filesUnder(paths.uploads)).map((path) => join(paths.uploads, path));
  const targets = [paths.data, paths.database, paths.private, paths.uploads, paths.staging, ...privateFiles.slice(0, 3), ...uploadFiles.slice(0, 3)];
  const attempts = hosted.readAsOtherUser(targets);
  const readable = Object.entries(attempts).filter(([, outcome]) => outcome !== 'EACCES');
  assert.deepEqual(readable, [], `${label}: another user could read site data`);
  return {
    entries: entries.length,
    files: entries.filter((entry) => !entry.directory).length,
    privateFiles: privateFiles.length,
    modes: Object.fromEntries(['data', 'database', 'private', 'uploads', 'staging'].map((name) => [name, mode(paths[name])?.toString(8) ?? null])),
    otherUser: hosted.otherUser,
    otherUserAttempts: Object.values(attempts).length,
    otherUserOutcomes: [...new Set(Object.values(attempts))],
  };
}

