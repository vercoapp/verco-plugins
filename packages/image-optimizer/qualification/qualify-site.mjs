/** Sharp-generated photograph-like JPEGs (gradient, texture and grain), saved heavier than needed. */
async function fixtures(sharp, count) {
  const images = [];
  for (let index = 0; index < count; index += 1) {
    const width = 1024;
    const height = 768;
    const hue = (index * 37) % 360;
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}">
      <defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
        <stop offset="0" stop-color="hsl(${hue},70%,55%)"/><stop offset="1" stop-color="hsl(${(hue + 140) % 360},60%,35%)"/>
      </linearGradient></defs>
      <rect width="100%" height="100%" fill="url(#g)"/>
      <circle cx="${300 + index * 40}" cy="380" r="${150 + index * 5}" fill="hsl(${(hue + 60) % 360},80%,70%)" opacity="0.6"/>
    </svg>`;
    const grain = await sharp({ create: { width, height, channels: 3, noise: { type: 'gaussian', mean: 128, sigma: 18 } } }).raw().toBuffer();
    const bytes = await sharp(Buffer.from(svg))
      .composite([{ input: grain, raw: { width, height, channels: 3 }, blend: 'overlay' }])
      .jpeg({ quality: 100, chromaSubsampling: '4:4:4' })
      .toBuffer();
    images.push({ name: `fixture-${String(index + 1).padStart(2, '0')}.jpg`, bytes, width, height });
  }
  return images;
}

/**
 * Images near the processor's limits (24 MP and 16 MiB in, lossless WebP 12 MP), photograph-like
 * like the fixtures above. The grain is lowered until each file is under the input limit.
 */
async function heavyFixtures(sharp) {
  const limit = 15 * 1024 * 1024;
  const make = async ({ name, width, height, type, encode }) => {
    for (const grain of [12, 8, 5, 3, 0]) {
      const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}">
        <defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
          <stop offset="0" stop-color="hsl(20,70%,55%)"/><stop offset="1" stop-color="hsl(200,60%,35%)"/>
        </linearGradient></defs>
        <rect width="100%" height="100%" fill="url(#g)"/>
        <circle cx="${width / 3}" cy="${height / 2}" r="${height / 3}" fill="hsl(90,80%,70%)" opacity="0.6"/>
      </svg>`;
      let image = sharp(Buffer.from(svg), { limitInputPixels: false });
      if (grain > 0) {
        const noise = await sharp({ create: { width, height, channels: 3, noise: { type: 'gaussian', mean: 128, sigma: grain } } }).raw().toBuffer();
        const raw = await image.composite([{ input: noise, raw: { width, height, channels: 3 }, blend: 'overlay' }]).removeAlpha().raw().toBuffer();
        image = sharp(raw, { raw: { width, height, channels: 3 } });
      }
      const bytes = await encode(image);
      if (bytes.length <= limit) return { name, width, height, type, bytes };
    }
    throw new Error(`${name} does not fit under the input limit`);
  };
  return [
    await make({ name: 'near-limit-24mp.jpg', width: 6000, height: 3990, type: 'image/jpeg', encode: (image) => image.jpeg({ quality: 95 }).toBuffer() }),
    await make({ name: 'near-limit-12mp.webp', width: 4000, height: 2990, type: 'image/webp', encode: (image) => image.webp({ quality: 95 }).toBuffer() }),
    await make({ name: 'near-limit-12mp-lossless.webp', width: 4000, height: 2990, type: 'image/webp', encode: (image) => image.webp({ lossless: true }).toBuffer() }),
  ];
}

